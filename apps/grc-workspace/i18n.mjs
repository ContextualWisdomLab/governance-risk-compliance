export const LOCALES = Object.freeze(['en', 'ko']);

export function messagesFor(locale) {
  return MESSAGES[locale] ?? MESSAGES.en;
}

export function applyLocale(root, locale) {
  const selected = LOCALES.includes(locale) ? locale : 'en';
  const messages = messagesFor(selected);
  for (const element of root.querySelectorAll('[data-i18n]')) {
    const value = messages[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  }
  for (const element of root.querySelectorAll('[data-i18n-attr]')) {
    const [attribute, key] = element.dataset.i18nAttr.split(':', 2);
    const value = messages[key];
    if (attribute && value !== undefined) element.setAttribute(attribute, value);
  }
  const documentElement = root.documentElement ?? root;
  documentElement.lang = selected;
  documentElement.dataset.locale = selected;
  return selected;
}
